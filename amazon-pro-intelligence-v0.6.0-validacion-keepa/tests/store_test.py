import os, sys, json, sqlite3, tempfile
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from backend.store import Store, Forbidden
R = []
def check(n, c):
    R.append((n, bool(c))); print(("OK   " if c else "FAIL ") + n)

p = os.path.join(tempfile.mkdtemp(), "t.db"); s = Store(p)
s.create_account("A", "AHT Suplementos", "AHT S.L.", "SC-A", ["amazon.es"]); s.create_account("B", "Otra marca", "Otra S.L.", "SC-B", ["amazon.de"])
s.create_user("ana", "contraseña-larga-1", "analyst", ["A"]); s.create_user("root", "contraseña-larga-2", "admin", [])
try: s.create_user("x", "corta", "analyst", []); check("rechaza contraseña corta", False)
except ValueError: check("rechaza contraseña corta", True)
check("login incorrecto → None", s.login("ana", "mala-contraseña-x") is None)
check("login usuario inexistente → None", s.login("nadie", "mala-contraseña-x") is None)
se = s.login("ana", "contraseña-larga-1"); sess = s.session(se["token"])
check("sesión válida con rol y cuentas", sess and sess["role"] == "analyst" and sess["accounts"] == ["A"])
check("token en BD solo como hash", se["token"] not in open(p, "rb").read().decode("latin1"))
check("cuentas visibles aisladas", [a["id"] for a in s.accounts_for(sess)] == ["A"])
check("admin ve todas", [a["id"] for a in s.accounts_for(s.session(s.login("root", "contraseña-larga-2")["token"]))] == ["A", "B"])
i = s.put("A", "dossier", {"x": 1}, key="magnesio", actor="ana")
check("lectura en su cuenta", s.get("A", i)["data"] == {"x": 1})
check("aislamiento: otra cuenta no lo ve", s.get("B", i) is None and s.list("B", "dossier") == [])
try: s.put("B", "dossier", {"x": 2}, id_=i); check("no se puede sobrescribir registro de otra cuenta", False)
except Forbidden: check("no se puede sobrescribir registro de otra cuenta", True)
check("no se borra desde otra cuenta", s.delete("B", i, "ana") is False and s.get("A", i))
s.put("A", "dossier", {"x": 3}, id_=i, actor="ana"); check("update conserva id", s.get("A", i)["data"] == {"x": 3})
try: s.put("A", "raro", {}); check("kind desconocido rechazado", False)
except ValueError: check("kind desconocido rechazado", True)
ok, n, bad = s.verify_audit(); check(f"cadena de auditoría íntegra ({n} entradas)", ok)
c = sqlite3.connect(p); c.execute("UPDATE audit SET detail='{\"id\":\"manipulado\"}' WHERE seq=(SELECT MIN(seq)+3 FROM audit)"); c.commit(); c.close()
s2 = Store(p); ok, n, bad = s2.verify_audit(); check(f"manipulación detectada (seq {bad})", (not ok) and bad)
s.logout(se["token"]); check("logout invalida sesión", s.session(se["token"]) is None)
tk = s.login("root", "contraseña-larga-2")["token"]; s.db.execute("UPDATE sessions SET expires=0"); s.db.commit()
check("sesión caducada rechazada", s.session(tk) is None)
f = sum(1 for _, c in R if not c); print(f"{len(R)-f}/{len(R)} OK"); sys.exit(1 if f else 0)
